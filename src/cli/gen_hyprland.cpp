#include "cli/gen_hyprland.hpp"

#include <algorithm>
#include <format>
#include <string_view>

namespace omenkbd {

namespace {

constexpr std::uint64_t kTickMs = 50;

// @WANTED@, @DELAY_MS@ and @TICKS@ are filled in by gen_hyprland().
constexpr std::string_view kTemplate =
    R"(-- generated by omen-kbd gen-hyprland: save as ~/.config/hypr/modules/kbdlight.lua and require it from hyprland.lua
-- (require("modules.kbdlight")). Holding a modifier set from [hints.modifiers] for DELAY_MS runs
-- `omen-kbd hint <set>`; releasing it runs `omen-kbd hint clear`. Only the 8 modifier keys are
-- tracked and nothing is logged. Re-run gen-hyprland after changing [hints] in config.toml.
local MODS = { [133] = "super", [134] = "super", [37] = "ctrl", [105] = "ctrl",
               [64] = "alt", [108] = "alt", [50] = "shift", [62] = "shift" }
local ORDER = { "super", "ctrl", "alt", "shift" }
local WANTED = {
@WANTED@}
local DELAY_MS = @DELAY_MS@
local TICK_MS = 50
local TICKS = @TICKS@ -- max(1, floor(DELAY_MS / TICK_MS))
local held, sent, pending, ticks_left = {}, false, nil, 0
-- Re-loading this module must never leave two live copies: older copies go quiet.
_G.omen_kbd_gen = (_G.omen_kbd_gen or 0) + 1
local GEN = _G.omen_kbd_gen
local function active() return _G.omen_kbd_gen == GEN end
local function current_set()
  local present, parts = {}, {}
  for code in pairs(held) do present[MODS[code]] = true end
  for _, m in ipairs(ORDER) do if present[m] then parts[#parts + 1] = m end end
  return table.concat(parts, "+")
end
-- One self-disabling repeat ticker (Hyprland destroys a single-fire timer once it fires); it runs
-- only while a wanted set is held and its hint has not shown yet.
local ticker
ticker = hl.timer(function()
  if not active() then ticker:set_enabled(false); return end
  ticks_left = ticks_left - 1
  if ticks_left > 0 then return end
  ticker:set_enabled(false)
  if pending ~= nil and pending == current_set() then
    hl.exec_cmd("omen-kbd hint " .. pending)
    sent = true
  end
end, { timeout = TICK_MS, type = "repeat" })
ticker:set_enabled(false)
hl.on("input.keyboard.key", function(keycode, _time, state)
  if not active() then return end
  if MODS[keycode] == nil then
    -- Another key pressed before the hint shows (a chord like Super+Q) cancels it.
    if state == 1 and ticks_left > 0 then
      ticker:set_enabled(false)
      ticks_left = 0
      pending = nil
    end
    return
  end
  if state == 2 then return end
  if state == 1 then held[keycode] = true else held[keycode] = nil end
  local set = current_set()
  ticker:set_enabled(false)
  ticks_left = 0
  pending = nil
  if WANTED[set] then
    pending = set
    ticks_left = TICKS
    ticker:set_enabled(true)
  elseif sent then
    hl.exec_cmd("omen-kbd hint clear")
    sent = false
  end
end)
)";

void replace(std::string &s, std::string_view key, std::string_view value) {
    const auto at = s.find(key);
    if (at != std::string::npos) {
        s.replace(at, key.size(), value);
    }
}

} // namespace

std::string gen_hyprland(const Config &cfg) {
    std::string wanted;
    for (const auto &[set, color] : cfg.hints.modifiers) { // keys are normalized and sorted
        wanted += std::format("  [\"{}\"] = true,\n", set);
    }
    std::string out(kTemplate);
    replace(out, "@WANTED@", wanted);
    replace(out, "@DELAY_MS@", std::to_string(cfg.hints.delay_ms));
    replace(out, "@TICKS@",
            std::to_string(std::max<std::uint64_t>(1, cfg.hints.delay_ms / kTickMs)));
    return out;
}

} // namespace omenkbd
